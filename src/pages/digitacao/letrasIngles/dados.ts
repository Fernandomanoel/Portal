export const FRASES_REACAO: Record<"correto" | "erro" | "bateman" | "sabrina", string[]> = {
  correto: ["Boa!", "Isso aí!", "Mandou bem!", "Sequência!"],
  erro: ["Ops!", "Quase…", "Tenta de novo!", "Foi por pouco!", "Presta atenção!"],
  bateman: ["Em chamas!", "Combo alto!", "Tá voando!"],
  sabrina: ["PERFEITO!", "Recompensa máxima!", "Lendário!"],
};

export function faceDeAcerto(combo: number): { src: string; nivel: keyof typeof FRASES_REACAO } {
  if (combo >= COMBO_SABRINA) return { src: GIF_SABRINA, nivel: "sabrina" };
  if (combo >= COMBO_BATEMAN) return { src: GIF_BATEMAN, nivel: "bateman" };
  const i = Math.max(0, Math.min(combo, FACES_CORRETO.length) - 1);
  return { src: FACES_CORRETO[i], nivel: "correto" };
}

export function faceDeErro(streak: number): string {
  const i = Math.max(0, Math.min(streak, FACES_ERRO.length) - 1);
  return FACES_ERRO[i];
}

